age = int(input())
if 0 <= age < 7:
    print("Дошкольник")
elif 7 <= age < 18:
    print("Школьник")
elif 18 <= age < 22:
    print("Студент")
elif 22 <= age < 65:
    print("Рабочий")
else:
    print("Пенсионер")
