# методы обработки списков


data = [8, 5, 9, 2]

# сортирует элементы списков в порядке возрастания
data.sort()

# сортирует элементы в порядке убывания
data.sort(reverse=True)

# сортирует элементы списков в порядке возрастания
data = sorted(data) #работает как методы обработки строк (изменяет копии)

print(data)

